// Language Management
class LanguageManager {
  constructor() {
    this.currentLanguage = localStorage.getItem("language") || "en"
    this.init()
  }

  init() {
    this.applyLanguage()
    this.bindEvents()
  }

  applyLanguage() {
    document.documentElement.setAttribute("lang", this.currentLanguage)
    localStorage.setItem("language", this.currentLanguage)

    // Update language buttons
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.lang === this.currentLanguage)
    })

    // Translate all elements
    this.translateElements()
  }

  translateElements() {
    const elements = document.querySelectorAll("[data-translate]")
    elements.forEach((element) => {
      const key = element.getAttribute("data-translate")
      const translation = translations[this.currentLanguage][key]
      if (translation) {
        element.innerHTML = translation
      }
    })
  }

  switchLanguage(lang) {
    this.currentLanguage = lang
    this.applyLanguage()
  }

  bindEvents() {
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.addEventListener("click", () => {
        this.switchLanguage(btn.dataset.lang)
      })
    })
  }
}

// Theme Management
class ThemeManager {
  constructor() {
    this.theme = localStorage.getItem("theme") || "light"
    this.init()
  }

  init() {
    this.applyTheme()
    this.bindEvents()
  }

  applyTheme() {
    document.documentElement.setAttribute("data-theme", this.theme)
    localStorage.setItem("theme", this.theme)
  }

  toggleTheme() {
    this.theme = this.theme === "light" ? "dark" : "light"
    this.applyTheme()
  }

  bindEvents() {
    const toggleButtons = document.querySelectorAll("#themeToggle, #mobileThemeToggle")
    toggleButtons.forEach((button) => {
      button.addEventListener("click", () => this.toggleTheme())
    })
  }
}

// Navigation Management
class NavigationManager {
  constructor() {
    this.header = document.getElementById("header")
    this.mobileMenuBtn = document.getElementById("mobileMenuBtn")
    this.mobileNav = document.getElementById("mobileNav")
    this.navLinks = document.querySelectorAll(".nav-link")
    this.init()
  }

  init() {
    this.bindEvents()
    this.handleScroll()
  }

  bindEvents() {
    // Mobile menu toggle
    this.mobileMenuBtn.addEventListener("click", () => this.toggleMobileMenu())

    // Navigation links
    this.navLinks.forEach((link) => {
      link.addEventListener("click", (e) => this.handleNavClick(e))
    })

    // Scroll event
    window.addEventListener("scroll", () => this.handleScroll())
  }

  toggleMobileMenu() {
    this.mobileMenuBtn.classList.toggle("active")
    this.mobileNav.classList.toggle("active")
  }

  handleNavClick(e) {
    e.preventDefault()
    const targetId = e.target.getAttribute("href")
    const targetElement = document.querySelector(targetId)

    if (targetElement) {
      const headerHeight = this.header.offsetHeight
      const targetPosition = targetElement.offsetTop - headerHeight

      window.scrollTo({
        top: targetPosition,
        behavior: "smooth",
      })
    }

    // Close mobile menu if open
    this.mobileMenuBtn.classList.remove("active")
    this.mobileNav.classList.remove("active")
  }

  handleScroll() {
    if (window.scrollY > 50) {
      this.header.classList.add("scrolled")
    } else {
      this.header.classList.remove("scrolled")
    }
  }
}

// Animation Manager
class AnimationManager {
  constructor() {
    this.observerOptions = {
      threshold: 0.1,
      rootMargin: "0px 0px -50px 0px",
    }
    this.init()
  }

  init() {
    this.createObserver()
    this.observeElements()
  }

  createObserver() {
    this.observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("animate")
        }
      })
    }, this.observerOptions)
  }

  observeElements() {
    const teamCards = document.querySelectorAll(".team-card")
    teamCards.forEach((card, index) => {
      card.style.transitionDelay = `${index * 100}ms`
      this.observer.observe(card)
    })
  }
}

// Project Filter Manager
class ProjectFilterManager {
  constructor() {
    this.filterButtons = document.querySelectorAll(".filter-btn")
    this.projectCards = document.querySelectorAll(".project-card")
    this.init()
  }

  init() {
    this.bindEvents()
  }

  bindEvents() {
    this.filterButtons.forEach((button) => {
      button.addEventListener("click", (e) => this.handleFilterClick(e))
    })
  }

  handleFilterClick(e) {
    const filterValue = e.target.getAttribute("data-filter")

    // Update active button
    this.filterButtons.forEach((btn) => btn.classList.remove("active"))
    e.target.classList.add("active")

    // Filter projects
    this.filterProjects(filterValue)
  }

  filterProjects(filter) {
    this.projectCards.forEach((card) => {
      const category = card.getAttribute("data-category")

      if (filter === "all" || category === filter) {
        card.classList.remove("hidden")
        setTimeout(() => {
          card.style.display = "block"
        }, 10)
      } else {
        card.classList.add("hidden")
        setTimeout(() => {
          if (card.classList.contains("hidden")) {
            card.style.display = "none"
          }
        }, 300)
      }
    })
  }
}

// Contact Form Manager
class ContactFormManager {
  constructor() {
    this.form = document.getElementById("contactForm")
    this.init()
  }

  init() {
    if (this.form) {
      this.bindEvents()
    }
  }

  bindEvents() {
    this.form.addEventListener("submit", (e) => this.handleSubmit(e))
  }

  handleSubmit(e) {
    e.preventDefault()

    const formData = new FormData(this.form)
    const data = Object.fromEntries(formData)

    // Simulate form submission
    this.showSuccessMessage()
    this.form.reset()
  }

  showSuccessMessage() {
    const button = this.form.querySelector('button[type="submit"]')
    const originalText = button.innerHTML
    const currentLang = localStorage.getItem("language") || "en"
    const successText = currentLang === "tr" ? "Mesaj Gönderildi!" : "Message Sent!"

    button.innerHTML = `<span>${successText}</span> <span>✅</span>`
    button.disabled = true

    setTimeout(() => {
      button.innerHTML = originalText
      button.disabled = false
    }, 3000)
  }
}

// Utility Functions
function scrollToSection(sectionId) {
  const element = document.getElementById(sectionId)
  if (element) {
    const headerHeight = document.getElementById("header").offsetHeight
    const targetPosition = element.offsetTop - headerHeight

    window.scrollTo({
      top: targetPosition,
      behavior: "smooth",
    })
  }
}

// Smooth scroll for anchor links
function initSmoothScroll() {
  document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
    anchor.addEventListener("click", function (e) {
      e.preventDefault()
      const target = document.querySelector(this.getAttribute("href"))
      if (target) {
        const headerHeight = document.getElementById("header").offsetHeight
        const targetPosition = target.offsetTop - headerHeight

        window.scrollTo({
          top: targetPosition,
          behavior: "smooth",
        })
      }
    })
  })
}

// Loading Animation
function initLoadingAnimations() {
  // Hero text animation
  const heroLines = document.querySelectorAll(".hero-line")
  heroLines.forEach((line, index) => {
    setTimeout(
      () => {
        line.style.opacity = "1"
        line.style.transform = "translateY(0)"
      },
      index * 500 + 500,
    )
  })

  // Hero subtitle and buttons
  setTimeout(() => {
    const subtitle = document.querySelector(".hero-subtitle")
    const buttons = document.querySelector(".hero-buttons")

    if (subtitle) {
      subtitle.style.opacity = "1"
      subtitle.style.transform = "translateY(0)"
    }

    if (buttons) {
      buttons.style.opacity = "1"
      buttons.style.transform = "translateY(0)"
    }
  }, 2000)
}

// Parallax Effect
function initParallaxEffect() {
  window.addEventListener("scroll", () => {
    const scrolled = window.pageYOffset
    const parallaxElements = document.querySelectorAll(".hero-bg")

    parallaxElements.forEach((element) => {
      const speed = 0.5
      element.style.transform = `translateY(${scrolled * speed}px)`
    })
  })
}

